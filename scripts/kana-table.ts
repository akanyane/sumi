const toKata = (s: string) =>
  s.replace(/[ぁ-ゖ]/g, (c) => String.fromCharCode(c.charCodeAt(0) + 0x60));

export type KanaOut = {
  k: string;
  script: "hiragana" | "katakana";
  r: string;
  row: string;
  col: number;
  group: KanaGroup;
  origin: string | null;
  pair: string;
  lk: string;
  ex: { w: string; r: string; g: string } | null;
};

export function buildKanaTable(): KanaOut[] {
  const out: KanaOut[] = [];
  const add = (h: string, row: string, col: number, group: KanaGroup) => {
    const romaji =
      group === "combo"
        ? (() => {
            const base = ROMAJI[h[0]];
            const v = { ゃ: "a", ゅ: "u", ょ: "o" }[h[1] as "ゃ"];
            return /^(shi|chi|ji)$/.test(base)
              ? base.slice(0, -1) + v
              : `${base.slice(0, -1)}y${v}`;
          })()
        : ROMAJI[h];
    for (const script of ["hiragana", "katakana"] as const) {
      const k = script === "hiragana" ? h : toKata(h);
      const pair = script === "hiragana" ? toKata(h) : h;
      const lkGroup = LOOKALIKE.find((g) => [...g].includes(k));
      const ex = EXAMPLES[k];
      out.push({
        k,
        script,
        r: romaji,
        row,
        col,
        group,
        origin: ORIGIN[k] ?? null,
        pair,
        lk: lkGroup ? [...lkGroup].filter((c) => c !== k).join("") : "",
        ex: ex ? { w: ex[0], r: ex[0], g: ex[1] } : null,
      });
    }
  };
  for (const g of [
    [BASIC, "basic"],
    [DAKUTEN, "dakuten"],
  ] as const)
    for (const { row, cells } of g[0])
      for (const [col, c] of cells.entries()) if (c) add(c, row, col, g[1]);
  for (const base of COMBO_BASES)
    for (const [col, s] of SMALL.entries())
      add(base + s, ROMAJI[base], col, "combo");
  return out;
}

